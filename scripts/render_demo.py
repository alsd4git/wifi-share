"""Capture the real image-export command using a synthetic Wi-Fi profile."""

from __future__ import annotations

import contextlib
import html
import io
import os
import re
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import wifi_share

SSID = "Demo Guest"
PASSWORD = "example-only-123"
FILENAME = "guest-demo.svg"
SVG_NAMESPACE = "http://www.w3.org/2000/svg"


def capture():
    """Generate a QR with explicit fake credentials; forbid system lookups."""
    output = io.StringIO()
    previous_directory = Path.cwd()
    with tempfile.TemporaryDirectory(prefix="wifi-share-demo-") as directory:
        try:
            os.chdir(directory)
            arguments = ["wifi-share", "--ssid", SSID, "--password", PASSWORD, "--image", FILENAME]
            with (
                patch.object(sys, "argv", arguments),
                patch.object(
                    wifi_share, "execute", side_effect=AssertionError("No system commands")
                ),
                patch.object(
                    wifi_share, "get_password", side_effect=AssertionError("No saved passwords")
                ),
                patch.object(
                    wifi_share,
                    "get_current_wifi_name",
                    side_effect=AssertionError("No Wi-Fi lookup"),
                ),
                patch.object(wifi_share, "fix_ownership"),
                patch.object(wifi_share, "verbose", False),
                contextlib.redirect_stdout(output),
            ):
                wifi_share.main()
            qr = ET.parse(FILENAME).getroot()
        finally:
            os.chdir(previous_directory)
    transcript = re.sub(r"\x1b\[[0-9;]*m", "", output.getvalue()).strip()
    if transcript != "[+] Qr code drawn in guest-demo.svg":
        raise RuntimeError(f"Unexpected CLI output: {transcript!r}")
    return qr, transcript


def render():
    qr, transcript = capture()
    ET.register_namespace("", SVG_NAMESPACE)
    qr.set("x", "260")
    qr.set("y", "130")
    qr.set("width", "440")
    qr.set("height", "440")
    qr_markup = ET.tostring(qr, encoding="unicode")
    command = 'wifi-share --ssid "Demo Guest" --password "example-only-123" --image guest-demo.svg'
    return f'''<svg xmlns="{SVG_NAMESPACE}" width="960" height="650" viewBox="0 0 960 650" role="img" aria-labelledby="title description">
  <title id="title">Wi-Fi Share image export with synthetic credentials</title>
  <desc id="description">QR code generated by the actual CLI for the fictitious Demo Guest network. No system credentials or real network were accessed.</desc>
  <rect width="960" height="650" rx="12" fill="#10151e"/>
  <g fill="#e5e9f0" font-family="monospace" xml:space="preserve">
    <text x="24" y="36" font-size="17">Wi-Fi Share · synthetic image-export demo</text>
    <text x="24" y="72" font-size="14">$ {html.escape(command)}</text>
    <text x="24" y="102" font-size="14">{html.escape(transcript)}</text>
  </g>
  {qr_markup}
  <text x="24" y="605" fill="#8993a4" font-family="monospace" font-size="15">Fictitious SSID and password · no system lookups · generated by the real CLI</text>
  <text x="24" y="631" fill="#8993a4" font-family="monospace" font-size="14">This QR encodes only the synthetic profile above, not a real guest network.</text>
</svg>
'''


if __name__ == "__main__":
    destination = ROOT / "docs" / "demo.svg"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render(), encoding="utf-8")
    print(f"Generated {destination.relative_to(ROOT)} without accessing saved Wi-Fi profiles.")
